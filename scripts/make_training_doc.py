def h(doc: Document, text: str, level: int = 1) -> None:
    doc.add_heading(text, level=level)


def p(doc: Document, text: str, bold: bool = False, italic: bool = False,
      size: int | None = None) -> None:
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = bold
    run.italic = italic
    if size:
        run.font.size = Pt(size)
    return par


def bullets(doc: Document, items: list[str], style: str = "List Bullet") -> None:
    for it in items:
        doc.add_paragraph(it, style=style)


def numbered(doc: Document, items: list[str]) -> None:
    for it in items:
        doc.add_paragraph(it, style="List Number")


def table(doc: Document, header: list[str], rows: list[list[str]],
          widths: list[float] | None = None) -> None:
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, text in enumerate(header):
        cell = t.rows[0].cells[j]
        cell.text = text
        cell.paragraphs[0].runs[0].bold = True
    for i, row in enumerate(rows, 1):
        for j, text in enumerate(row):
            t.rows[i].cells[j].text = text
    if widths:
        for j, w in enumerate(widths):
            for r in t.rows:
                r.cells[j].width = Cm(w)


def box(doc: Document, text: str) -> None:
    """Врезка «важно» — абзац в рамке через таблицу из одной ячейки."""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Light Grid Accent 1"
    cell = t.rows[0].cells[0]
    cell.text = text
    cell.paragraphs[0].runs[0].bold = True
    doc.add_paragraph()


